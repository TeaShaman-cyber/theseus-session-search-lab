BEGIN;
CREATE ROLE session_search_owner NOLOGIN;
GRANT session_search_owner TO CURRENT_USER WITH INHERIT FALSE, SET TRUE;
CREATE ROLE session_search_reader NOLOGIN;
CREATE ROLE session_search_materializer NOLOGIN;
ALTER SCHEMA session_search OWNER TO session_search_owner;
ALTER TABLE session_search.generations OWNER TO session_search_owner;
ALTER TABLE session_search.sessions OWNER TO session_search_owner;
ALTER TABLE session_search.messages OWNER TO session_search_owner;
ALTER TABLE session_search.active_generation OWNER TO session_search_owner;
ALTER FUNCTION session_search.safe_message_search_vector(text) OWNER TO session_search_owner;
ALTER FUNCTION session_search.mark_generation_ready(text,text,integer,integer) OWNER TO session_search_owner;
ALTER FUNCTION session_search.activate_generation(text,text) OWNER TO session_search_owner;
ALTER FUNCTION session_search.search_generation(text,text,text[],integer,text,double precision,double precision) OWNER TO session_search_owner;
ALTER FUNCTION session_search.search(text,text[],integer,text,double precision,double precision) OWNER TO session_search_owner;
ALTER FUNCTION session_search.generation_status() OWNER TO session_search_owner;
SET LOCAL ROLE session_search_owner;
ALTER DEFAULT PRIVILEGES FOR ROLE session_search_owner REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA session_search FROM PUBLIC;
REVOKE ALL ON SCHEMA session_search FROM PUBLIC;
REVOKE ALL ON ALL TABLES IN SCHEMA session_search FROM PUBLIC;
GRANT USAGE ON SCHEMA session_search TO session_search_reader,session_search_materializer;
GRANT SELECT,INSERT ON session_search.generations TO session_search_materializer;
GRANT SELECT,INSERT ON session_search.sessions TO session_search_materializer;
GRANT SELECT,INSERT ON session_search.messages TO session_search_materializer;
GRANT EXECUTE ON FUNCTION session_search.mark_generation_ready(text,text,integer,integer) TO session_search_materializer;
GRANT EXECUTE ON FUNCTION session_search.activate_generation(text,text) TO session_search_materializer;
GRANT EXECUTE ON FUNCTION session_search.search_generation(text,text,text[],integer,text,double precision,double precision) TO session_search_reader,session_search_materializer;
GRANT EXECUTE ON FUNCTION session_search.search(text,text[],integer,text,double precision,double precision) TO session_search_reader;
GRANT EXECUTE ON FUNCTION session_search.generation_status() TO session_search_reader,session_search_materializer;
RESET ROLE;
COMMIT;
